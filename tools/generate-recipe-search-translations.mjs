import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

// レシピ検索用に、レシピで使うアイテムIDとその各言語での名前の対応表を生成する。
//
// 言語ファイルの場所:
//   MAKECOUNTRY_RP_TEXTS  MakeCountryResourcePack/texts (既定: このパックと同じ親フォルダ)
//   VANILLA_TEXTS         バニラの resource_packs/vanilla/texts (任意。BDS などに同梱)
const packRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const recipeSourceRoots = [
    join(packRoot, "src/content/cooking"),
    join(packRoot, "src/content/chemical"),
    join(packRoot, "src/content/smelting"),
];
const translationRoots = [
    process.env.MAKECOUNTRY_RP_TEXTS ?? join(packRoot, "..", "MakeCountryResourcePack", "texts"),
    ...(process.env.VANILLA_TEXTS ? [process.env.VANILLA_TEXTS] : []),
].filter((root) => existsSync(root));
const outputPath = join(packRoot, "src/generated/recipe-search-translations.ts");

async function filesWithExtension(directory, extension) {
    const entries = await readdir(directory, { withFileTypes: true });
    const nested = await Promise.all(entries.map(async (entry) => {
        const path = join(directory, entry.name);
        if (entry.isDirectory()) return filesWithExtension(path, extension);
        return entry.isFile() && entry.name.endsWith(extension) ? [path] : [];
    }));
    return nested.flat();
}

async function collectRecipeItemIds() {
    const ids = new Set();
    for (const root of recipeSourceRoots) {
        for (const path of await filesWithExtension(root, ".ts")) {
            const source = await readFile(path, "utf8");
            for (const match of source.matchAll(/["'`](minecraft|mc):([a-z0-9_./-]+)["'`]/gi)) {
                ids.add(`${match[1].toLowerCase()}:${match[2].toLowerCase()}`);
            }
        }
    }
    return ids;
}

function identifierForTranslationKey(key) {
    const custom = key.match(/^(?:item|tile)\.mc:([a-z0-9_./-]+?)(?:\.name)?$/i);
    if (custom) return `mc:${custom[1].toLowerCase()}`;

    const vanilla = key.match(/^(?:item|tile)\.([a-z0-9_./-]+)\.name$/i);
    if (vanilla) return `minecraft:${vanilla[1].toLowerCase()}`;

    return undefined;
}

function readLangEntries(source) {
    const entries = [];
    for (const rawLine of source.replace(/^﻿/, "").split(/\r?\n/)) {
        const line = rawLine.trim();
        if (!line || line.startsWith("#")) continue;
        const separator = line.indexOf("=");
        if (separator <= 0) continue;
        const key = line.slice(0, separator).trim();
        const value = line.slice(separator + 1).trim();
        if (value) entries.push([key, value]);
    }
    return entries;
}

if (!translationRoots.length) {
    throw new Error("言語ファイルが見つかりません。MAKECOUNTRY_RP_TEXTS に MakeCountryResourcePack/texts を指定してください。");
}

const recipeItemIds = await collectRecipeItemIds();
const translations = new Map([...recipeItemIds].map((id) => [id, new Set()]));

for (const root of translationRoots) {
    for (const path of (await filesWithExtension(root, ".lang")).sort()) {
        const source = await readFile(path, "utf8");
        for (const [key, value] of readLangEntries(source)) {
            const identifier = identifierForTranslationKey(key);
            if (identifier && translations.has(identifier)) translations.get(identifier).add(value);
        }
    }
}

const catalog = Object.fromEntries(
    [...translations]
        .filter(([, values]) => values.size > 0)
        // Build output must not depend on the shell/cron locale.
        .sort(([left], [right]) => left < right ? -1 : left > right ? 1 : 0)
        .map(([id, values]) => [id, [...values].sort()])
);

const source = `// Generated by tools/generate-recipe-search-translations.mjs. Do not edit by hand.\n` +
    `export const RECIPE_SEARCH_TRANSLATIONS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(catalog, null, 4)};\n`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, source);
console.log(
    `Generated translations for ${Object.keys(catalog).length}/${recipeItemIds.size} recipe item identifiers ` +
    `in ${relative(packRoot, outputPath)}.`
);
