import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const packRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const itemsRoot = join(packRoot, "items");
const outputPath = join(packRoot, "src/generated/item-characteristics.ts");

async function jsonFiles(directory) {
    const entries = await readdir(directory, { withFileTypes: true });
    const nested = await Promise.all(entries.map(async (entry) => {
        const path = join(directory, entry.name);
        if (entry.isDirectory()) return jsonFiles(path);
        return entry.isFile() && entry.name.endsWith(".json") ? [path] : [];
    }));
    return nested.flat();
}

function explicitDestroySpeeds(digger) {
    return (digger?.destroy_speeds ?? [])
        .filter((entry) => typeof entry.block === "string" && typeof entry.speed === "number")
        .map((entry) => ({ blockId: entry.block, speed: entry.speed }));
}

function genericDestroySpeed(digger) {
    const speeds = (digger?.destroy_speeds ?? [])
        .filter((entry) => typeof entry.block === "object" && typeof entry.speed === "number")
        .map((entry) => entry.speed);
    return speeds.length > 0 ? Math.max(...speeds) : undefined;
}

function compactSpecialMining(entries) {
    const groups = [
        ["obsidian", "smelting.effect.special.obsidian", (id) => id === "minecraft:obsidian"],
        ["deepslate", "smelting.effect.special.deepslate", (id) => id.includes("deepslate")],
        ["logs", "smelting.effect.special.logs", (id) => id.includes("_log") || id.includes("_wood")],
        ["glass", "smelting.effect.special.glass", (id) => id.includes("glass")],
    ];

    const result = [];
    const consumed = new Set();
    for (const [, translationKey, matches] of groups) {
        const matched = entries.filter((entry) => matches(entry.blockId));
        if (matched.length === 0) continue;
        matched.forEach((entry) => consumed.add(entry));
        result.push({ translationKey, speed: Math.max(...matched.map((entry) => entry.speed)) });
    }

    for (const entry of entries.filter((candidate) => !consumed.has(candidate)).slice(0, 4)) {
        result.push({ blockId: entry.blockId, speed: entry.speed });
    }
    return result;
}

const catalog = {};
for (const path of [...await jsonFiles(itemsRoot)].sort()) {
    let document;
    try {
        document = JSON.parse(await readFile(path, "utf8"));
    } catch (error) {
        throw new Error(`Invalid item JSON: ${relative(packRoot, path)}\n${error}`);
    }

    const item = document["minecraft:item"];
    const identifier = item?.description?.identifier;
    const components = item?.components;
    if (!identifier || !components) continue;

    const durability = components["minecraft:durability"]?.max_durability;
    const attackDamage = components["minecraft:damage"];
    const protection = components["minecraft:wearable"]?.protection;
    const nutrition = components["minecraft:food"]?.nutrition;
    const digger = components["minecraft:digger"];
    const miningSpeed = genericDestroySpeed(digger);
    const specialMining = compactSpecialMining(explicitDestroySpeeds(digger));
    const rankedTool = components["mc:ranktool"] !== undefined;

    if (
        durability === undefined &&
        attackDamage === undefined &&
        protection === undefined &&
        nutrition === undefined &&
        miningSpeed === undefined &&
        specialMining.length === 0 &&
        !rankedTool
    ) continue;

    catalog[identifier] = {
        ...(typeof attackDamage === "number" ? { attackDamage } : {}),
        ...(typeof durability === "number" ? { durability } : {}),
        ...(typeof protection === "number" ? { protection } : {}),
        ...(typeof nutrition === "number" ? { nutrition } : {}),
        ...(typeof miningSpeed === "number" ? { miningSpeed } : {}),
        ...(specialMining.length > 0 ? { specialMining } : {}),
        ...(rankedTool ? { rankedTool: true } : {}),
    };
}

const source = `// Generated by tools/generate-item-characteristics.mjs. Do not edit by hand.\n` +
`export type SpecialMiningCharacteristic = { translationKey?: string; blockId?: string; speed: number };\n` +
`export type ItemCharacteristics = {\n` +
`    attackDamage?: number;\n` +
`    durability?: number;\n` +
`    protection?: number;\n` +
`    nutrition?: number;\n` +
`    miningSpeed?: number;\n` +
`    specialMining?: SpecialMiningCharacteristic[];\n` +
`    rankedTool?: boolean;\n` +
`};\n\n` +
`export const ITEM_CHARACTERISTICS: Record<string, ItemCharacteristics> = ${JSON.stringify(catalog, null, 4)};\n`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, source);
console.log(`Generated ${Object.keys(catalog).length} item characteristic entries.`);
