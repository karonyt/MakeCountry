// Small deterministic pixel textures, matching the existing generated furniture.
function crc32(data) {
    let crc = 0xffffffff;
    for (const byte of data) { crc ^= byte; for (let n = 0; n < 8; n++) crc = (crc >>> 1) ^ ((crc & 1) ? 0xedb88320 : 0); }
    return (crc ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
    const name = Buffer.from(type), size = Buffer.alloc(4), crc = Buffer.alloc(4);
    size.writeUInt32BE(data.length); crc.writeUInt32BE(crc32(Buffer.concat([name, data])));
    return Buffer.concat([size, name, data, crc]);
}
function png(file, pixels, size = 32) {
    const raw = Buffer.alloc((size * 4 + 1) * size);
    for (let y = 0; y < size; y++) pixels.copy(raw, y * (size * 4 + 1) + 1, y * size * 4, (y + 1) * size * 4);
    const header = Buffer.alloc(13); header.writeUInt32BE(size); header.writeUInt32BE(size, 4); header[8] = 8; header[9] = 6;
    writeGeneratedPng(file, Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', header), chunk('IDAT', zlib.deflateSync(raw)), chunk('IEND', Buffer.alloc(0))]));
}
const shift = (c, n) => c.map(v => Math.min(255, Math.max(0, v + n)));
function pixels() {
    const data = Buffer.alloc(32 * 32 * 4);
    return { data, rect(x, y, w, h, color) {
        for (let py = y; py < y + h; py++) for (let px = x; px < x + w; px++) {
            if (px < 0 || px >= 32 || py < 0 || py >= 32) continue;
            data.set([...color.slice(0, 3), color[3] ?? 255], (py * 32 + px) * 4);
        }
    } };
}
